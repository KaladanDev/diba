/// Flutter's round slider thumb with a ring inside its edge, so it keeps
/// its size: the ring is [_thumbRingWidth] wide inside the 20-wide thumb,
/// which leaves a slate core 14 across.
///
/// The thumb is slate-700, the colour on the gilt, in both themes, and half of
/// it sits on the empty track. In the dark theme that track is slate-700 too,
/// and without the ring the thumb vanished into it (1.00:1). The gilt ring is
/// 5.88:1 against that track and 9.14:1 against the dark card.
