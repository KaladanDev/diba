sd.registerFormat({
  name: 'diba/dart',
  format: ({ dictionary }) => {
    const all = dictionary.allTokens as unknown as Tok[]
    const byPath = indexByPath(all)
    const colors = all.filter((t) => typeOf(t) === 'color')

    /** A semantic token's value in one mode, resolved through any reference. */
    const modeValue = (t: Tok, dark: boolean) =>
      toLiteral(dark ? (darkRaw(t) ?? rawValue(t)) : rawValue(t), byPath)

    /**
     * A colour that will not convert is a build failure, not a token to drop.
     * Skipping it silently would leave the Dart missing a member that the
     * theme below still names, and the only place that surfaces is someone
     * else's `flutter run`.
     */
    const colorLine = (t: Tok, value: string) => {
      const c = dartColor(value)
      if (!c) throw new Error(`Dart target: cannot convert ${t.name} = "${value}" to sRGB.`)
      return `  static const Color ${camel(t.name)} = ${c};`
    }

    const semanticColors = colors.filter(isSemantic)
    const colorBody = (dark: boolean) => semanticColors.map((t) => colorLine(t, modeValue(t, dark)))

    const palette = colors.filter((t) => !isSemantic(t)).map((t) => colorLine(t, litValue(t)))

    const scalars = (group: string, type: 'double' | 'Duration') =>
      all
        .filter((t) => t.path[0] === group)
        .flatMap((t) => {
          const v = type === 'Duration' ? dartMs(litValue(t)) : dartLength(litValue(t))
          if (!v) return []
          return [`  static const ${type} ${member(t.name, group)} = ${v};`]
        })

    /** Unitless ratios — line height, opacity — which need no conversion. */
    const ratios = (group: string) =>
      all
        .filter((t) => t.path[0] === group && /^[\d.]+$/.test(litValue(t)))
        .map((t) => `  static const double ${member(t.name, group)} = ${litValue(t)};`)

    const weights = all
      .filter((t) => t.path[0] === 'weight')
      .map(
        (t) =>
          `  static const FontWeight ${member(t.name, 'weight')} = FontWeight.w${litValue(t)};`,
      )

    /** Every length token, so a custom widget can reach the same numbers the CSS does. */
    const dimens = all
      .filter((t) => typeOf(t) === 'dimension' && dartLength(litValue(t)))
      .map((t) => `  static const double ${camel(t.name)} = ${dartLength(litValue(t))};`)

    const fonts = all
      .filter((t) => t.path[0] === 'font' && t.path[1] === 'family')
      .map(
        (t) =>
          `  static const String ${member(t.name, 'font-family')} = '${firstFamily(litValue(t))}';`,
      )

    return (
      /*
       * A line comment, not a block one. Dart nests block comments, and the
       * shared header says `Source: src/tokens/**.` — that `/*` opens a second
       * level the single closing delimiter never shuts, so the whole file was
       * one unterminated comment. It typechecked nowhere because nothing here
       * could compile Dart; `flutter analyze` found it on line 1.
       */
      header('Flutter target. OKLCH is resolved to sRGB here — Dart cannot do it at runtime.')
        .replace('/* ', '// ')
        .replace(' */', '') +
      `\n// ignore_for_file: unused_element\nimport 'package:flutter/material.dart';\n\n` +
      dartClass('DibaLightColors', 'Semantic colours, light theme.', colorBody(false)) +
      '\n' +
      dartClass('DibaDarkColors', 'Semantic colours, dark theme.', colorBody(true)) +
      '\n' +
      dartClass('DibaPalette', 'The primitive ramps. Mode-agnostic.', palette) +
      '\n' +
      dartClass('DibaRadius', 'Corner radii, in logical pixels.', scalars('radius', 'double')) +
      '\n' +
      dartClass('DibaSpace', 'The spacing scale, in logical pixels.', scalars('space', 'double')) +
      '\n' +
      dartClass('DibaFontSize', 'The type scale, in logical pixels.', scalars('text', 'double')) +
      '\n' +
      dartClass('DibaLineHeight', 'Line height as a multiple of font size.', ratios('leading')) +
      '\n' +
      dartClass('DibaFontWeight', 'Weights.', weights) +
      '\n' +
      dartClass('DibaOpacity', 'Opacities.', ratios('opacity')) +
      '\n' +
      dartClass('DibaMotion', 'Durations.', scalars('duration', 'Duration')) +
      '\n' +
      dartClass('DibaFonts', 'Family names. Bundle these in pubspec.yaml.', fonts) +
      '\n' +
      dartClass('DibaDimens', 'Every length token, for widgets built by hand.', dimens) +
      '\n' +
      DART_THEME
    )
  },
})

await sd.buildAllPlatforms()

