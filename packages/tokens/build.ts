/**
 * Diba tokens build — ONE OKLCH source → many platforms.
 *
 * Style Dictionary parses + resolves the token graph; custom formats emit:
 *   - dist/theme.css       :root primitives + light/dark semantic selectors
 *   - dist/tailwind.css    Tailwind v4 `@theme inline` layer (tokens → utilities)
 *   - dist/tokens.js/.d.ts  typed CSS-var refs + resolved values (light/dark)
 *   - dist/native/DibaTokens.dart  Flutter: sRGB colors, scales, and a Material 3 ThemeData
 *
 * Semantic colors are dual-mode: light in `$value`, dark in
 * `$extensions.diba.dark`. Everything else is mode-agnostic (lives in :root).
 */
import { copyFileSync, existsSync, mkdirSync } from 'node:fs'
import StyleDictionary from 'style-dictionary'
import type { DesignTokens } from 'style-dictionary/types'

type Tok = {
  name: string
  path: string[]
  value?: unknown
  $value?: unknown
  type?: string
  $type?: string
  filePath?: string
  original: { $value?: unknown; value?: unknown; $extensions?: Extensions }
  $extensions?: Extensions
}
type Extensions = { diba?: { dark?: string } }

const REF = /^\{([^}]+)\}$/

/**
 * Namespace for every CSS variable this package emits. Diba ships precompiled
 * CSS into merchant storefronts and third-party plugins, so bare names like
 * `--primary` or `--bg` would be a coin flip against whatever else is on the
 * page. Tailwind's theme keys (`--color-primary`, `--radius-md`) stay bare —
 * they only exist to name utilities and never reach the document.
 */
const NS = 'db'
/** The emitted CSS variable name for a token, e.g. `db-primary`. */
const cssName = (t: Tok): string => `${NS}-${t.name}`

const litValue = (t: Tok): string => String(t.value !== undefined ? t.value : t.$value)
const rawValue = (t: Tok): string =>
  String(t.original?.$value !== undefined ? t.original.$value : t.original?.value)
const darkRaw = (t: Tok): string | undefined =>
  (t.$extensions ?? t.original?.$extensions)?.diba?.dark
const typeOf = (t: Tok): string => String(t.$type ?? t.type ?? '')
const isSemantic = (t: Tok): boolean => !!t.filePath && t.filePath.includes('semantic')

/** Emit `var(--db-ref)` for a token reference, or the literal value otherwise. */
function toCss(raw: string, byPath: Map<string, Tok>): string {
  const m = raw.match(REF)
  if (m?.[1]) {
    const ref = byPath.get(m[1])
    if (ref) return `var(--${cssName(ref)})`
  }
  return raw
}

/** Resolve a reference (or literal) to its concrete OKLCH/value string. */
function toLiteral(raw: string, byPath: Map<string, Tok>): string {
  const m = raw.match(REF)
  if (m?.[1]) {
    const ref = byPath.get(m[1])
    if (ref) return litValue(ref)
  }
  return raw
}

const header = (what: string) =>
  `/* GENERATED by @kaladan/diba-tokens — DO NOT EDIT. Source: src/tokens/**. ${what} */\n`

/**
 * Collision guard. Style Dictionary deep-merges every source file, so a name used
 * as a *group* in one file and a *token* in another (e.g. primitive `border.sm`
 * vs semantic `border`) silently loses one side. Count the leaves as each file is
 * parsed and compare against what actually got emitted. Must be registered on the
 * class — an instance resolves its parser list synchronously at construction.
 */
let sourceLeaves = 0
let emittedTokens = -1
const countLeaves = (node: unknown): number => {
  if (typeof node !== 'object' || node === null) return 0
  if ('$value' in node) return 1
  return Object.values(node).reduce<number>((n, v) => n + countLeaves(v), 0)
}

StyleDictionary.registerParser({
  name: 'diba/leaf-count',
  pattern: /\.json$/,
  parser: ({ contents }) => {
    const parsed = JSON.parse(contents) as DesignTokens
    sourceLeaves += countLeaves(parsed)
    return parsed
  },
})

