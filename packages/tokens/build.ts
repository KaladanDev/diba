/**
 * OKLCH → sRGB, resolved at build time.
 *
 * Dart has no OKLCH parser and Flutter's `Color` is sRGB, so the conversion has
 * to happen here or not at all. Shipping the OKLCH strings — which is what the
 * stub did — pushes an unsolved problem across the language boundary and calls
 * it a pipeline.
 */
function oklchToRgb(L: number, C: number, H: number): [number, number, number] {
  const h = (H * Math.PI) / 180
  const a = C * Math.cos(h)
  const b = C * Math.sin(h)

  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3

  return [
    +4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ]
}

const inGamut = ([r, g, b]: [number, number, number]) =>
  [r, g, b].every((c) => c >= -0.0001 && c <= 1.0001)

/**
 * Bring an out-of-gamut colour back by reducing chroma, not by clipping
 * channels. Clipping shifts hue — a saturated garnet clips its blue channel
 * and slides orange — which is exactly the kind of drift nobody notices until
 * two platforms are side by side.
 */
function gamutMap(L: number, C: number, H: number): [number, number, number] {
  if (inGamut(oklchToRgb(L, C, H))) return oklchToRgb(L, C, H)
  let lo = 0
  let hi = C
  for (let i = 0; i < 24; i++) {
    const mid = (lo + hi) / 2
    if (inGamut(oklchToRgb(L, mid, H))) lo = mid
    else hi = mid
  }
  return oklchToRgb(L, lo, H)
}

const toSrgb = (c: number) => {
  const v = c <= 0.0031308 ? 12.92 * c : 1.055 * Math.pow(c, 1 / 2.4) - 0.055
  return Math.max(0, Math.min(255, Math.round(v * 255)))
}

const OKLCH = /^oklch\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)\s*(?:\/\s*([\d.]+)\s*)?\)$/

/** A CSS colour value as a Dart `Color(0xAARRGGBB)` literal, or null. */
function dartColor(value: string): string | null {
  const m = value.trim().match(OKLCH)
  if (!m) return null
  const [L, C, H] = [Number(m[1]), Number(m[2]), Number(m[3])]
  const alpha = m[4] === undefined ? 1 : Number(m[4])
  const [r, g, b] = gamutMap(L, C, H).map(toSrgb) as [number, number, number]
  const hex = [Math.round(alpha * 255), r, g, b]
    .map((n) => n.toString(16).padStart(2, '0').toUpperCase())
    .join('')
  return `Color(0x${hex})`
}

/** `12px` / `1.5rem` → logical pixels. Flutter has one unit, so rem is resolved. */
function dartLength(value: string): string | null {
  const m = value.trim().match(/^(-?[\d.]+)(px|rem)$/)
  if (!m) return null
  // Dart takes an int literal where a double is expected, so 12 and 12.5 both
  // read fine as `static const double`.
  return String(Number(m[1]) * (m[2] === 'rem' ? 16 : 1))
}

const dartMs = (value: string): string | null => {
  const m = value.trim().match(/^([\d.]+)ms$/)
  return m ? `Duration(milliseconds: ${Math.round(Number(m[1]))})` : null
}

/** First family off a CSS stack — Flutter takes one name plus a fallback list. */
const firstFamily = (stack: string) =>
  (stack.split(',')[0] ?? '').trim().replace(/^['"]|['"]$/g, '')

/** `primary-fg` → `primaryFg`. */
const camel = (s: string) => s.replace(/-(.)/g, (_, c: string) => c.toUpperCase())

/**
 * `radius-md` → `md`, but `space-4` → `space4`: a Dart identifier cannot start
 * with a digit, so numeric steps keep their prefix.
 */
function member(name: string, group: string): string {
  const bare = camel(name.slice(group.length + 1))
  return /^\d/.test(bare) ? camel(name) : bare
}

const dartClass = (name: string, doc: string, body: string[]) =>
  `/// ${doc}\nabstract final class ${name} {\n  const ${name}._();\n\n${body.join('\n')}\n}\n`

