const indexByPath = (tokens: Tok[]) => new Map(tokens.map((t) => [t.path.join('.'), t]))

sd.registerFormat({
  name: 'diba/theme-css',
  format: ({ dictionary }) => {
    const all = dictionary.allTokens as unknown as Tok[]
    emittedTokens = all.length
    const byPath = indexByPath(all)
    const primitives = all.filter((t) => !isSemantic(t))
    const semantic = all.filter(isSemantic)

    const root = primitives.map((t) => `  --${cssName(t)}: ${litValue(t)};`).join('\n')
    const light = semantic
      .map((t) => `  --${cssName(t)}: ${toCss(rawValue(t), byPath)};`)
      .join('\n')
    const dark = semantic
      .map((t) => `  --${cssName(t)}: ${toCss(darkRaw(t) ?? rawValue(t), byPath)};`)
      .join('\n')

    return (
      header('CSS variables. Theme = swap the semantic selector.') +
      `\n:root {\n${root}\n}\n` +
      `\n:root,\n[data-theme='light'] {\n${light}\n}\n` +
      `\n[data-theme='dark'] {\n${dark}\n}\n`
    )
  },
})

sd.registerFormat({
  name: 'diba/tailwind-css',
  format: ({ dictionary }) => {
    const all = dictionary.allTokens as unknown as Tok[]
    /** Tailwind theme key (bare — it only names a utility) → the namespaced var. */
    const line = (key: string, t: Tok) => `  --${key}: var(--${cssName(t)});`

    const colors = all.filter((t) => typeOf(t) === 'color').map((t) => line(`color-${t.name}`, t))
    const radius = all.filter((t) => t.path[0] === 'radius').map((t) => line(t.name, t))
    const text = all.filter((t) => t.path[0] === 'text').map((t) => line(t.name, t))
    const weight = all
      .filter((t) => t.path[0] === 'weight')
      .map((t) => line(`font-weight-${t.path[1]}`, t))
    const leading = all
      .filter((t) => t.path[0] === 'leading')
      .map((t) => line(`leading-${t.path[1]}`, t))
    const tracking = all
      .filter((t) => t.path[0] === 'tracking')
      .map((t) => line(`tracking-${t.path[1]}`, t))
    const family = all
      .filter((t) => t.path[0] === 'font' && t.path[1] === 'family')
      .map((t) => line(`font-${t.path[2]}`, t))
    const shadow = all.filter((t) => t.path[0] === 'shadow').map((t) => line(t.name, t))
    const ease = all
      .filter((t) => t.path[0] === 'easing')
      .map((t) => line(`ease-${t.path.slice(1).join('-')}`, t))
    const blur = all.filter((t) => t.path[0] === 'blur').map((t) => line(t.name, t))

    const section = (title: string, lines: string[]) =>
      lines.length ? `\n  /* ${title} */\n${lines.join('\n')}\n` : ''

    return (
      header('Tailwind v4 theme layer — maps tokens to utilities (bg-primary, rounded-md, …).') +
      `@import './theme.css';\n\n` +
      `@theme inline {` +
      section('color', colors) +
      section('radius', radius) +
      section('font family', family) +
      section('font size', text) +
      section('font weight', weight) +
      section('line height', leading) +
      section('letter spacing', tracking) +
      section('shadow', shadow) +
      section('easing', ease) +
      section('blur', blur) +
      `\n  /* spacing base unit */\n  --spacing: 0.25rem;\n` +
      `}\n`
    )
  },
})

sd.registerFormat({
  name: 'diba/tokens-js',
  format: ({ dictionary }) => {
    const all = dictionary.allTokens as unknown as Tok[]
    const byPath = indexByPath(all)
    const cssVars: Record<string, string> = {}
    const light: Record<string, string> = {}
    const dark: Record<string, string> = {}
    for (const t of all) {
      cssVars[t.name] = `var(--${cssName(t)})`
      light[t.name] = litValue(t)
      if (isSemantic(t)) dark[t.name] = toLiteral(darkRaw(t) ?? rawValue(t), byPath)
    }
    return (
      header('Typed token refs + resolved values.').replace('/*', '//').replace('*/', '') +
      `export const cssVars = ${JSON.stringify(cssVars, null, 2)}\n\n` +
      `export const values = {\n  light: ${JSON.stringify(light, null, 2)},\n  dark: ${JSON.stringify(dark, null, 2)},\n}\n`
    )
  },
})

sd.registerFormat({
  name: 'diba/tokens-dts',
  format: ({ dictionary }) => {
    const all = dictionary.allTokens as unknown as Tok[]
    const keys = all.map((t) => `  readonly '${t.name}': 'var(--${cssName(t)})'`).join('\n')
    return (
      header('Types for token refs.').replace('/*', '//').replace('*/', '') +
      `export declare const cssVars: {\n${keys}\n}\n\n` +
      `export declare const values: {\n  readonly light: Readonly<Record<string, string>>\n  readonly dark: Readonly<Record<string, string>>\n}\n`
    )
  },
})

